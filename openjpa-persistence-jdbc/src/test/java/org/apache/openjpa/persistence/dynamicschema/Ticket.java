package org.apache.openjpa.persistence.dynamicschema;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.SequenceGenerator;

/**
 * An entity whose identity is generated by a sequence generator named after
 * a word Derby rejects as an unquoted sequence name, which names no sequence,
 * so that the generator name is the default sequence name.
 */
@Entity
public class Ticket {

    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "Window")
    @SequenceGenerator(name = "Window", allocationSize = 1)
    private long id;

    private String subject;

    public long getId() {
        return id;
    }

    public String getSubject() {
        return subject;
    }

    public void setSubject(String subject) {
        this.subject = subject;
    }
}
