package org.apache.openjpa.persistence.dynamicschema.names;


import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.SequenceGenerator;

/**
 * An entity whose relation to {@link Order} and whose sequence have a
 * reserved word as their name.
 */
@Entity
public class Item {

    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "ItemSequence")
    @SequenceGenerator(name = "ItemSequence", sequenceName = "Rank")
    private long id;

    @ManyToOne
    private Order order;

    private String trigger;
}
