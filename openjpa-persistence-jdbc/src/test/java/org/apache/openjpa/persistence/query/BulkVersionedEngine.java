package org.apache.openjpa.persistence.query;

import jakarta.persistence.Entity;
import jakarta.persistence.Table;

/**
 * Subclass of {@link BulkVersionedPart} in its own joined table.
 */
@Entity
@Table(name = "BMT_ENGINE")
public class BulkVersionedEngine extends BulkVersionedPart {

    private int power;

    public BulkVersionedEngine() {
    }

    public BulkVersionedEngine(long id, int quantity, int power) {
        super(id, quantity);
        this.power = power;
    }

    public int getPower() {
        return power;
    }

    public void setPower(int power) {
        this.power = power;
    }
}
