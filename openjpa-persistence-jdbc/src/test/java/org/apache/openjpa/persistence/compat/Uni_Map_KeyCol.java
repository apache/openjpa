package org.apache.openjpa.persistence.compat;

import java.util.HashMap;
import java.util.Map;

import jakarta.persistence.CollectionTable;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;

// Map of basic types without @MapKeyColumn, i.e. the key column name is
// derived from the default. Used to verify the compatibility option
// UseSpecDefaultMapKeyColumnName.
@Entity
public class Uni_Map_KeyCol {

    @Id
    @GeneratedValue
    private long id;

    private String name;

    @ElementCollection(fetch=FetchType.EAGER)
    @CollectionTable(name="Uni_Map_KeyCol_attrs",
        joinColumns=@JoinColumn(name="UniMapKeyCol_ID"))
    private Map<String, String> attributes = new HashMap<>();

    public long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public Map<String, String> getAttributes() {
        return attributes;
    }

    public void setAttributes(Map<String, String> attributes) {
        this.attributes = attributes;
    }
}
